#!/usr/bin/env python3
"""Secrets tool for brocast.

Default mode renders the three Secret manifests from secrets.env (+ SSH key
files) without touching the cluster: fastapi-secret.yaml,
brocast-app.yaml, box-ssh.yaml.

With --generate it first rotates the self-controlled values inside
secrets.env (DB_PASSWORD plus the JWT ES256 JWK set: D/X/Y/KID, which must
always rotate together) and then renders. Provider-issued keys,
DB_USER/POSTGRES_DB and the stable JWT identity fields (SUB/ISS/AUD) are
never touched.

Rotation consequences (fresh install only without migration!):
- new JWT set: all existing tokens stop validating (forced re-login).
- new DB_PASSWORD: synced by CNPG, then restart api/worker/cron pods.

Usage:
  ./manage_secrets.py [--env-file PATH] [--generate] [--yes]
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import sys
from typing import Dict, List, Tuple

import yaml
from cryptography.hazmat.backends import default_backend
from cryptography.hazmat.primitives.asymmetric import ec

HERE = os.path.dirname(os.path.abspath(__file__))
NAMESPACE = "broer"

# Keys regenerated by --generate (D/X/Y/KID always as one set).
GENERATED_KEYS = (
    "DB_PASSWORD",
    "JWT_D",
    "JWT_X",
    "JWT_Y",
    "JWT_KID",
)

# Derived from DB_USER/DB_PASSWORD at render time: input lines with these
# names are ignored so there is exactly one source of truth per credential.
LEGACY_IGNORED = (
    "POSTGRES_USER",
    "POSTGRES_PASSWORD",
    "username",
    "password",
)


def _b64url_uint(n: int) -> str:
    """JWK base64url encoding of a P-256 coordinate (32 bytes, no padding)."""
    return base64.urlsafe_b64encode(n.to_bytes(32, "big")).rstrip(b"=").decode("ascii")


def generate_fresh_values() -> Dict[str, str]:
    """Generate a DB password plus a fresh ES256 JWK signing set."""
    private_key = ec.generate_private_key(ec.SECP256R1(), default_backend())
    numbers = private_key.private_numbers()
    public = numbers.public_numbers
    fresh = {
        "DB_PASSWORD": secrets.token_hex(16),
        "JWT_D": _b64url_uint(numbers.private_value),
        "JWT_X": _b64url_uint(public.x),
        "JWT_Y": _b64url_uint(public.y),
        "JWT_KID": secrets.token_hex(16),
    }
    # Round-trip check: D must rebuild the same key.
    rebuilt = ec.derive_private_key(numbers.private_value, ec.SECP256R1())
    assert isinstance(rebuilt, ec.EllipticCurvePrivateKey)
    assert rebuilt.private_numbers().public_numbers.x == public.x
    assert rebuilt.private_numbers().public_numbers.y == public.y
    return fresh


def parse_env_file(path: str) -> Tuple[List[str], Dict[str, int]]:
    """Return raw lines plus key -> line index (data lines only)."""
    with open(path, encoding="utf-8") as handle:
        lines = handle.read().splitlines()
    index: Dict[str, int] = {}
    for i, line in enumerate(lines):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key = stripped.split("=", 1)[0].strip()
        index[key] = i
    return lines, index


def apply_fresh_values(path: str, fresh: Dict[str, str]) -> List[str]:
    """Replace generated keys in place, preserving comments/order. Returns changed keys."""
    lines, index = parse_env_file(path)
    missing = [key for key in GENERATED_KEYS if key not in index]
    if missing:
        raise SystemExit(f"ABORT: {path} lacks keys (outdated template?): {missing}")
    changed = []
    for key in GENERATED_KEYS:
        i = index[key]
        old_value = lines[i].split("=", 1)[1]
        if old_value != fresh[key]:
            lines[i] = f"{key}={fresh[key]}"
            changed.append(key)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return changed


def split_env_file(path: str) -> Tuple[List[str], List[str]]:
    """Split into (db_lines, app_lines), mapping descriptive DB names."""
    db_lines: List[str] = []
    app_lines: List[str] = []
    _, index = parse_env_file(path)
    with open(path, encoding="utf-8") as handle:
        raw = handle.read().splitlines()
    for i, line in enumerate(raw):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        key = key.strip()
        if key in LEGACY_IGNORED:
            print(
                f"  NOTE: ignoring legacy '{key}=' line (renamed, see secrets.env.example)",
                file=sys.stderr,
            )
            continue
        if key == "DB_USER":
            # CNPG wants username/password; the app reads POSTGRES_USER/PASSWORD.
            db_lines.append(f"username={value.strip()}")
            db_lines.append(f"POSTGRES_USER={value.strip()}")
        elif key == "DB_PASSWORD":
            db_lines.append(f"password={value.strip()}")
            db_lines.append(f"POSTGRES_PASSWORD={value.strip()}")
        elif key == "POSTGRES_DB":
            db_lines.append(line.strip())
        else:
            app_lines.append(line.strip())
    _ = index
    return db_lines, app_lines


def render_secret(
    name: str,
    secret_type: str | None,
    out_path: str,
    env_lines: List[str] | None = None,
    from_files: Dict[str, str] | None = None,
    namespace: str = NAMESPACE,
) -> None:
    """Create Secret manifest."""
    data: Dict[str, str] = {}
    for line in env_lines or []:
        key, _, value = line.partition("=")
        data[key.strip()] = base64.b64encode(value.strip().encode("utf-8")).decode(
            "ascii"
        )
    for key, src in (from_files or {}).items():
        with open(src, "rb") as handle:
            data[key] = base64.b64encode(handle.read()).decode("ascii")
    manifest: Dict[str, object] = {
        "apiVersion": "v1",
        "kind": "Secret",
        "metadata": {"name": name, "namespace": namespace},
        "data": data,
    }
    if secret_type:
        manifest["type"] = secret_type
    header = "# GENERATED by manage_secrets.py - DO NOT COMMIT - DO NOT EDIT\n"
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(header)
        yaml.safe_dump(
            manifest, handle, sort_keys=True, default_flow_style=False, width=10**6
        )
    os.chmod(out_path, 0o600)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--env-file", default=os.path.join(HERE, "secrets.env"), help="secrets source"
    )
    parser.add_argument(
        "--generate",
        action="store_true",
        help="rotate self-controlled values in secrets.env first (see warnings above)",
    )
    parser.add_argument(
        "--yes", action="store_true", help="skip the rotation confirmation prompt"
    )
    args = parser.parse_args()

    src = args.env_file
    if not os.path.isfile(src):
        print(f"MISSING: {src}\n  cp secrets.env.example secrets.env && fill + re-run")
        return 1

    if args.generate:
        if not args.yes and sys.stdin.isatty():
            answer = input(
                "Rotate DB/JWT keys in secrets.env? "
                "This logs out users. Type ROTATE to confirm: "
            )
            if answer.strip() != "ROTATE":
                print("Aborted.")
                return 1
        fresh = generate_fresh_values()
        changed = apply_fresh_values(src, fresh)
        print(f"rotated in {src}: {', '.join(changed)}")

    with open(src, encoding="utf-8") as handle:
        content = handle.read()
    if "CHANGE_ME" in content:
        print(
            "ABORT: CHANGE_ME placeholders still present in secrets.env. "
            "Fill all values first, then re-run.\n"
            "  (refusing to render placeholders as real secrets; literal TODO values are allowed)"
        )
        return 1

    out_db = os.path.join(HERE, "fastapi-secret.yaml")
    out_app = os.path.join(HERE, "brocast-app.yaml")
    out_ssh = os.path.join(HERE, "box-ssh.yaml")
    key_file = os.path.join(HERE, "bro-box-id_ed25519")
    known_hosts_file = os.path.join(HERE, "box-known_hosts")

    db_lines, app_lines = split_env_file(src)

    print(f"[1/3] write {out_db} (overwritten if it exists)")
    render_secret(
        "fastapi-secret", "kubernetes.io/basic-auth", out_db, env_lines=db_lines
    )
    print(f"  wrote {out_db}")

    print(f"[2/3] write {out_app} (overwritten if it exists)")
    render_secret("brocast-app", None, out_app, env_lines=app_lines)
    print(f"  wrote {out_app}")

    print("[3/3] write box-ssh (key files, never env)")
    have_ssh = os.path.isfile(key_file) and os.path.isfile(known_hosts_file)
    if have_ssh:
        render_secret(
            "box-ssh",
            None,
            out_ssh,
            from_files={"id_ed25519": key_file, "known_hosts": known_hosts_file},
        )
        print(f"  wrote {out_ssh}")
    else:
        print(
            "  SKIP: key files missing (see secrets.env.example Box section)",
            file=sys.stderr,
        )

    print("[4/4] verify rendered manifests (keys only, no values printed)")
    to_check = [(out_db, "fastapi-secret"), (out_app, "brocast-app")]
    if have_ssh:
        to_check.append((out_ssh, "box-ssh"))
    for path, expected_name in to_check:
        with open(path, encoding="utf-8") as handle:
            doc = yaml.safe_load(handle)  # leading # GENERATED line is a comment
        assert doc["metadata"]["name"] == expected_name, path
        print(f"  {expected_name}: keys={sorted(doc.get('data', {}))}")
    print(
        "Done. Apply with: kubectl apply -k <kubernetes-dir>\n"
        "If you changed values, restart consumers:\n"
        f"  kubectl -n {NAMESPACE} rollout restart "
        "deploy/fastapi-deployment deploy/worker-deployment "
        "deploy/cron-worker-deployment\n"
        "  (cronjobs pick it up on next schedule)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
